def apply_locale(locale: str, table: dict[str, str]) -> None:
    ts_path = TS_DIR / f"v_{locale}.ts"
    if not ts_path.exists():
        return
    tree = ET.parse(ts_path)
    root = tree.getroot()
    changed = 0
    for msg in root.iter("message"):
        source = msg.find("source")
        translation = msg.find("translation")
        if source is None or translation is None or source.text is None:
            continue
        src = source.text
        if src in table:
            translation.text = table[src]
            if "type" in translation.attrib:
                del translation.attrib["type"]
            changed += 1
    ET.indent(tree, space="    ")
    tree.write(ts_path, encoding="utf-8", xml_declaration=True)
    print(f"{locale}: updated {changed} entries")


def main() -> None:
    for locale, table in TRANS.items():
        apply_locale(locale, table)


if __name__ == "__main__":
    main()
